// Builds src/routes.generated.ts: the list of every API route the Express
// server registers, read from the folder layout under src/api/.
//
// The folder layout IS the URL, exactly as it was under Next.js:
//   src/api/students/[id]/route.ts  →  /api/students/:id
//
// Run automatically before dev, build and test (see package.json). The test
// suite also fails if the committed file is out of date, so a new route
// folder can never be silently missing from the server.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const serverRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apiDir = path.join(serverRoot, "src", "api");
const outFile = path.join(serverRoot, "src", "routes.generated.ts");

function findRouteFiles(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...findRouteFiles(full));
    else if (entry.name === "route.ts") found.push(full);
  }
  return found;
}

function toSegments(file) {
  const rel = path.relative(apiDir, path.dirname(file));
  return rel === "" ? [] : rel.split(path.sep);
}

function toExpressPath(segments) {
  const parts = segments.map((s) => {
    const m = /^\[(\w+)\]$/.exec(s);
    if (m) return ":" + m[1];
    if (!/^[\w-]+$/.test(s)) {
      throw new Error(`Unsupported route folder name "${s}" — use plain names or [param].`);
    }
    return s;
  });
  return "/api" + (parts.length ? "/" + parts.join("/") : "");
}

// Next.js always prefers a fixed segment over a [param] at the same depth
// (/students/import beats /students/[id]). Express matches in registration
// order, so register fixed segments first to keep the same behaviour.
function compareRoutes(a, b) {
  const n = Math.max(a.segments.length, b.segments.length);
  for (let i = 0; i < n; i++) {
    const x = a.segments[i];
    const y = b.segments[i];
    if (x === undefined) return -1;
    if (y === undefined) return 1;
    const xDyn = x.startsWith("[");
    const yDyn = y.startsWith("[");
    if (xDyn !== yDyn) return xDyn ? 1 : -1;
    if (x !== y) return x < y ? -1 : 1;
  }
  return 0;
}

export function buildRoutesSource() {
  const routes = findRouteFiles(apiDir)
    .map((file) => ({ file, segments: toSegments(file) }))
    .sort(compareRoutes);

  const imports = routes.map((r, i) => {
    const rel = "./" + path.relative(path.join(serverRoot, "src"), r.file).split(path.sep).join("/").replace(/\.ts$/, "");
    return `import * as r${i} from "${rel}";`;
  });
  const entries = routes.map((r, i) => `  { path: "${toExpressPath(r.segments)}", handlers: r${i} },`);

  return [
    "// AUTO-GENERATED by scripts/generate-routes.mjs from the folders in src/api/.",
    "// Do not edit by hand — add or remove a src/api/**/route.ts and re-run `npm run routes`.",
    'import type { RouteModule } from "./lib/http/route-types";',
    ...imports,
    "",
    "export const routes: ReadonlyArray<{ path: string; handlers: RouteModule }> = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const source = buildRoutesSource();
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== source) {
    fs.writeFileSync(outFile, source);
    console.log(`routes: wrote ${path.relative(serverRoot, outFile)}`);
  } else {
    console.log("routes: up to date");
  }
}
